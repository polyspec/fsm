// Tests of the npm backend (packages/status-compiler/src/backends/npm.mjs, docs/spec/status.md, B-4 and B-6): the files of the
// order example are the golden files under tests/golden/npm, byte for byte, in the order the backend returns them, and the
// vector module is the golden tests/vectors.mjs. The golden files were written by the generator once, after a review of its
// output against B-6 (docs/plans/status-v1.md, C-5).
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { files, vectorsFile } from '../src/backends/npm.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { vectors } from '../src/core/vectors.mjs';
import { jsonStore } from '../src/store-json/store.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const GOLDEN = path.join(HERE, 'golden/npm');
const NAMES = ['order.js', 'order.d.ts', 'status.js', 'status.d.ts', 'index.js', 'index.d.ts'];
const HEADER = /^\/\/ Code generated by status-gen from [^\n]+; DO NOT EDIT\.\n/;

/** The IRs and the lock of the repository's definitions (the order example). */
async function orderIrs() {
  const { definitions, lock, findings } = await jsonStore(ROOT).load();
  assert.deepEqual(findings, []);
  return { irs: definitions.map(normalize), lock };
}

test('the files of the order example are the golden files, byte for byte, in the backend order', async () => {
  const { irs, lock } = await orderIrs();
  const out = files(irs, lock);
  assert.deepEqual(out.map(file => file.path), NAMES);
  for (const file of out) {
    assert.equal(file.content, readFileSync(path.join(GOLDEN, 'src', file.path), 'utf8'), `${file.path} differs from its golden file`);
  }
});

test('every generated file starts with the status-gen header of its machine or of status', async () => {
  const { irs, lock } = await orderIrs();
  for (const file of files(irs, lock)) {
    assert.match(file.content, HEADER, file.path);
    const from = file.path.startsWith('order.') ? 'order' : 'status';
    assert.equal(file.content.split('\n')[0], `// Code generated by status-gen from ${from}; DO NOT EDIT.`, file.path);
    assert.ok(file.content.endsWith('\n') && !file.content.endsWith('\n\n'), `${file.path} must end with exactly one line break`);
  }
});

test('the vector module of the order example is the golden tests/vectors.mjs, byte for byte', async () => {
  const { irs, lock } = await orderIrs();
  const generated = irs.map(ir => vectors(ir, lock));
  assert.equal(vectorsFile(generated), readFileSync(path.join(GOLDEN, 'vectors.mjs'), 'utf8'));
});

test('the backend is deterministic: the same input gives the same files', async () => {
  const { irs, lock } = await orderIrs();
  assert.deepEqual(files(irs, lock), files(irs, lock));
});

/** The generated files of the order example with reserved code 9, written to a temporary directory and imported from it. */
async function importedWithReserved(t) {
  const { irs } = await orderIrs();
  const root = mkdtempSync(path.join(tmpdir(), 'status-npm-backend-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(path.join(root, 'src'));
  writeFileSync(path.join(root, 'package.json'), '{"type":"module"}\n');
  for (const file of files(irs, { order: { codes: {}, reserved: [9] } })) {
    if (file.path.endsWith('.js')) writeFileSync(path.join(root, 'src', file.path), file.content);
  }
  const api = await import(pathToFileURL(path.join(root, 'src/index.js')).href);
  return { order: api.order, status: api.status };
}

/** Asserts that `fn` throws a status.Error with `code`, and returns the error. */
function assertThrowsCode(status, fn, code) {
  let caught;
  try {
    fn();
  } catch (error) {
    caught = error;
  }
  assert.ok(caught instanceof status.Error, `expected a status.Error with ${code}, got ${caught}`);
  assert.equal(caught.code, code);
  assert.equal(typeof caught.message, 'string');
  return caught;
}

test('fromCode: a reserved code is E_RESERVED_CODE, and every other non-state value is E_UNKNOWN_CODE', async (t) => {
  const { order, status } = await importedWithReserved(t);
  assert.equal(order.fromCode(1), order.State.Draft);
  assertThrowsCode(status, () => order.fromCode(9), 'E_RESERVED_CODE');
  for (const value of [0, 6, -1, 1.5, 2 ** 53 + 2, 2147483648, '1', null, undefined, NaN]) {
    assertThrowsCode(status, () => order.fromCode(value), 'E_UNKNOWN_CODE');
  }
});

test('the state functions check their state, and a value that is no state is E_UNKNOWN_CODE', async (t) => {
  const { order, status } = await importedWithReserved(t);
  assertThrowsCode(status, () => order.code(7), 'E_UNKNOWN_CODE');
  assertThrowsCode(status, () => order.key(9), 'E_UNKNOWN_CODE');
  assertThrowsCode(status, () => order.isFinal('1'), 'E_UNKNOWN_CODE');
  assertThrowsCode(status, () => order.eventsFrom(0), 'E_UNKNOWN_CODE');
  assertThrowsCode(status, () => order.target(0, order.Event.Next), 'E_UNKNOWN_CODE');
  assert.equal(order.code(order.State.Paid), 2);
  assert.equal(order.key(order.State.Paid), 'paid');
  assert.equal(order.isFinal(order.State.Done), true);
  assert.equal(order.isFinal(order.State.Draft), false);
  assert.deepEqual(order.eventsFrom(order.State.Draft), [order.Event.Next, order.Event.Cancel]);
  assert.deepEqual(order.eventsFrom(order.State.Done), []);
  assert.equal(order.initial(), order.State.Draft);
});

test('target: an event without an edge from the state is E_INVALID_TRANSITION with the arguments', async (t) => {
  const { order, status } = await importedWithReserved(t);
  assert.equal(order.target(order.State.Paid, order.Event.Prev), order.State.Draft);
  const error = assertThrowsCode(status, () => order.target(order.State.Done, order.Event.Next), 'E_INVALID_TRANSITION');
  assert.equal(error.expected, order.State.Done);
  assert.equal(error.event, order.Event.Next);
  assertThrowsCode(status, () => order.target(order.State.Draft, 99), 'E_INVALID_TRANSITION');
});

test('apply: Changed, Unchanged, E_CONFLICT with its fields, and an unknown stored state is E_UNKNOWN_CODE', async (t) => {
  const { order, status } = await importedWithReserved(t);
  const { Draft, Paid, Shipped } = order.State;
  const next = order.Event.Next;
  assert.deepEqual(order.apply(Draft, next, Draft), { to: Paid, changed: true });
  assert.deepEqual(order.apply(Draft, next, Paid), { to: Paid, changed: false });
  const conflict = assertThrowsCode(status, () => order.apply(Draft, next, Shipped), 'E_CONFLICT');
  assert.deepEqual([conflict.expected, conflict.actual, conflict.event], [Draft, Shipped, next]);
  assertThrowsCode(status, () => order.apply(Draft, next, 7), 'E_UNKNOWN_CODE');
  assertThrowsCode(status, () => order.apply(Draft, order.Event.Prev, Draft), 'E_INVALID_TRANSITION');
});
