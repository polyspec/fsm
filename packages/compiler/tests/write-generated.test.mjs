// Tests of the git-ignored files of the output directory of gen (docs/plans/fsm-v1/checklist.md, S-14-3): an ignored file is a
// build output, not a hand-written file, so gen neither refuses it with E_NOT_GENERATED nor removes it as stale. A tracked file or
// a file that Git does not ignore still gives E_NOT_GENERATED. Outside a git work tree nothing counts as ignored. Every case runs
// in a temporary directory that is removed when the file's tests end.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import test, {  } from 'node:test';
import { HERE, gen, tempDir } from './cli-support.mjs';
import { ORDER_PROJECT } from './order-project.mjs';

const GOLDEN = path.join(HERE, 'golden/npm');

/** A new temporary git repository whose output directory is `src/` (created). */
function gitRepo(ignore) {
  const root = tempDir();
  const init = spawnSync('git', ['init', '-q', root], { encoding: 'utf8' });
  assert.equal(init.status, 0, init.stderr);
  writeFileSync(path.join(root, '.gitignore'), ignore);
  const out = path.join(root, 'src');
  mkdirSync(out);
  return { root, out };
}

const genNpm = out => gen(['gen', '--project', ORDER_PROJECT, '--kind', 'npm', '--out', out]);
const golden = name => readFileSync(path.join(GOLDEN, 'src', name), 'utf8');

/** Asserts that gen into `out` is refused for the hand-written order.js: E_NOT_GENERATED, exit 1, the file kept, nothing else written. */
function assertRefusesHandWritten(out) {
  const result = genNpm(out);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /^\[fsm-gen\] E_NOT_GENERATED - order\.js: /m);
  assert.equal(readFileSync(path.join(out, 'order.js'), 'utf8'), 'export const hand = 1;\n');
  assert.equal(existsSync(path.join(out, 'fsm.js')), false);
}

test('gen in a git work tree writes the generated files and leaves an ignored file without the header untouched', () => {
  const { out } = gitRepo('src/build.o\n');
  writeFileSync(path.join(out, 'build.o'), 'phpize output\n');
  assert.deepEqual(genNpm(out), { status: 0, stdout: '[fsm-gen] gen: ok\n', stderr: '' });
  assert.equal(readFileSync(path.join(out, 'build.o'), 'utf8'), 'phpize output\n');
  for (const name of ['order.js', 'order.d.ts', 'fsm.js', 'fsm.d.ts', 'index.js', 'index.d.ts']) {
    assert.equal(readFileSync(path.join(out, name), 'utf8'), golden(name), name);
  }
});

test('gen still refuses a non-ignored hand-written file: E_NOT_GENERATED, exit 1, and nothing written', () => {
  const { out } = gitRepo('src/build.o\n');
  writeFileSync(path.join(out, 'order.js'), 'export const hand = 1;\n');
  assertRefusesHandWritten(out);
});

test('gen still refuses a tracked file, even when a pattern of .gitignore names it', () => {
  const { root, out } = gitRepo('src/order.js\n');
  writeFileSync(path.join(out, 'order.js'), 'export const hand = 1;\n');
  const add = spawnSync('git', ['-C', root, 'add', '-f', 'src/order.js'], { encoding: 'utf8' });
  assert.equal(add.status, 0, add.stderr);
  assertRefusesHandWritten(out);
});

test('gen does not remove an ignored file as stale, even one that carries the generated header', () => {
  const { out } = gitRepo('src/stale.js\n');
  const stale = '// Code generated by fsm-gen from gone; DO NOT EDIT.\nexport {};\n';
  writeFileSync(path.join(out, 'stale.js'), stale);
  assert.equal(genNpm(out).status, 0);
  assert.equal(readFileSync(path.join(out, 'stale.js'), 'utf8'), stale);
  assert.equal(readFileSync(path.join(out, 'order.js'), 'utf8'), golden('order.js'));
});

test('outside a git work tree a file without the header gives E_NOT_GENERATED, and nothing is written', () => {
  const out = path.join(tempDir(), 'src');
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'build.o'), 'phpize output\n');
  const result = genNpm(out);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /^\[fsm-gen\] E_NOT_GENERATED - build\.o: /m);
  assert.equal(readFileSync(path.join(out, 'build.o'), 'utf8'), 'phpize output\n');
  assert.equal(existsSync(path.join(out, 'order.js')), false);
});
