// Tests of the php-ext backend (packages/compiler/src/backends/php-ext.mjs, docs/spec/fsm.md, B-4 and B-6): the files of
// the order example are the golden files under tests/golden/php-ext/src, byte for byte, in the order the backend returns them.
// The test module is the golden tests/golden/php-ext/ConformanceTest.php, which equals the php golden ConformanceTest.php byte for byte, because
// the php-ext package runs the same tests (docs/plans/fsm-v1.md, C-2). The golden files were written by the generator once,
// after a review of its output against B-6 (docs/plans/fsm-v1.md, C-5). The config.m4 and the stub are checked by their own
// tools in the package tests; here the stub passes the php linter, and the namespace and the extension name that the command
// line passes are refused when they are not valid.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { files, vectorsFile } from '../src/backends/php-ext.mjs';
import { files as phpFiles, vectorsFile as phpVectorsFile } from '../src/backends/php.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { vectors } from '../src/core/vectors.mjs';
import { jsonStore } from '../src/store-json/store.mjs';
import { ORDER_PROJECT } from './order-project.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const GOLDEN = path.join(HERE, 'golden/php-ext');
const GOLDEN_PHP = path.join(HERE, 'golden/php');
const NAMESPACE = 'Polyspec\\FsmTest';
const EXT = 'polyspec_fsm_test';
const NAMES = [
  'order.c',
  'fsm.c',
  'php_polyspec_fsm_test.h',
  'polyspec_fsm_test_arginfo.h',
  'polyspec_fsm_test.stub.php',
  'config.m4',
];

/** The IRs and the lock of the repository's definitions (the order example). */
async function orderIrs() {
  const { definitions, lock, findings } = await jsonStore(ORDER_PROJECT).load();
  assert.deepEqual(findings, []);
  return { irs: definitions.map(normalize), lock };
}

/** The files of the order example for the namespace and the extension name of the package. */
async function orderFiles() {
  const { irs, lock } = await orderIrs();
  return files(irs, lock, { phpNamespace: NAMESPACE, phpExtName: EXT });
}

test('the files of the order example are the golden files, byte for byte, in the backend order', async () => {
  const out = await orderFiles();
  assert.deepEqual(out.map(file => file.path), NAMES);
  for (const file of out) {
    assert.equal(file.content, readFileSync(path.join(GOLDEN, 'src', file.path), 'utf8'), `${file.path} differs from its golden file`);
  }
});

test('every generated file carries the fsm-gen header of its machine or of fsm, in its own comment syntax, with one final line break', async () => {
  for (const file of await orderFiles()) {
    const from = file.path === 'order.c' ? 'order' : 'fsm';
    const header = file.path === 'config.m4' ? `dnl Code generated by fsm-gen from ${from}; DO NOT EDIT.`
      : `// Code generated by fsm-gen from ${from}; DO NOT EDIT.`;
    const lines = file.content.split('\n');
    if (file.path.endsWith('.stub.php')) assert.equal(lines[0], '<?php', file.path);
    assert.equal(file.path.endsWith('.stub.php') ? lines[1] : lines[0], header, file.path);
    assert.ok(file.content.endsWith('\n') && !file.content.endsWith('\n\n'), `${file.path} must end with exactly one line break`);
  }
});

test('the test module is the php golden ConformanceTest.php, byte for byte, and equals the php backend output', async () => {
  const { irs, lock } = await orderIrs();
  const generated = irs.map(ir => vectors(ir, lock));
  const module = vectorsFile(generated, { phpNamespace: NAMESPACE });
  assert.equal(module, readFileSync(path.join(GOLDEN, 'ConformanceTest.php'), 'utf8'));
  assert.equal(module, readFileSync(path.join(GOLDEN_PHP, 'ConformanceTest.php'), 'utf8'));
  assert.equal(module, phpVectorsFile(generated, { phpNamespace: NAMESPACE }));
});

test('the backend is deterministic and the php src files are not part of its output', async () => {
  const { irs, lock } = await orderIrs();
  assert.deepEqual(files(irs, lock, { phpNamespace: NAMESPACE, phpExtName: EXT }), files(irs, lock, { phpNamespace: NAMESPACE, phpExtName: EXT }));
  assert.equal(phpFiles(irs, lock, { phpNamespace: NAMESPACE }).some(file => file.path.endsWith('.c')), false);
});

test('the namespace and the extension name are required and must be valid, otherwise nothing is generated', async () => {
  const { irs, lock } = await orderIrs();
  for (const phpNamespace of [undefined, '', 'Bad Name', '\\Polyspec', 'Polyspec\\', 'Polyspec\\\\FsmTest', '1Fsm', 'Poly-spec']) {
    assert.throws(() => files(irs, lock, { phpNamespace, phpExtName: EXT }), /php namespace/, JSON.stringify(phpNamespace));
    assert.throws(() => vectorsFile([], { phpNamespace }), /php namespace/, JSON.stringify(phpNamespace));
  }
  for (const phpExtName of [undefined, '', 'Polyspec', '1ext', 'poly-spec', 'poly spec']) {
    assert.throws(() => files(irs, lock, { phpNamespace: NAMESPACE, phpExtName }), /php extension name/, JSON.stringify(phpExtName));
  }
});

test('the fsm stub passes the php linter (php -l)', async (t) => {
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-php-ext-backend-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const stub = (await orderFiles()).find(file => file.path.endsWith('.stub.php'));
  const target = path.join(dir, stub.path);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, stub.content);
  const lint = spawnSync('php', ['-l', target], { encoding: 'utf8' });
  assert.equal(lint.status, 0, `${stub.path}: ${lint.stdout}${lint.stderr}`);
});

// A second namespace and extension name, which the package does not use: every name of the output must derive from them.
const OTHER_NAMESPACE = 'Acme\\Tool';
const OTHER_EXT = 'acme_tool';

test('every name of the output derives from the namespace and the extension name, with a second pair', async () => {
  const { irs, lock } = await orderIrs();
  const out = files(irs, lock, { phpNamespace: OTHER_NAMESPACE, phpExtName: OTHER_EXT });
  for (const file of out) assert.doesNotMatch(file.content, /Polyspec|polyspec|FsmTest|fsm_test/, file.path);
  const order = out.find(file => file.path === 'order.c').content;
  assert.match(order, /^#include "php_acme_tool\.h"$/m);
  assert.match(order, /^#include "acme_tool_arginfo\.h"$/m);
  const fsm = out.find(file => file.path === 'fsm.c').content;
  assert.match(fsm, /^ZEND_METHOD\(Acme_Tool_Fsm_Error, __construct\)$/m);
  assert.match(fsm, /^\tZEND_ME\(Acme_Tool_Fsm_Error, __construct, /m);
});

test('the extension builds with phpize, ./configure and make under a second name, and its namespace is registered', async (t) => {
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-php-ext-build-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const { irs, lock } = await orderIrs();
  for (const file of files(irs, lock, { phpNamespace: OTHER_NAMESPACE, phpExtName: OTHER_EXT })) {
    const target = path.join(dir, file.path);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, file.content);
  }
  for (const [command, args] of [['phpize', []], [path.join(dir, 'configure'), ['--enable-acme-tool']], ['make', []]]) {
    const run = spawnSync(command, args, { cwd: dir, encoding: 'utf8' });
    assert.equal(run.status, 0, `${command}: ${run.stdout}${run.stderr}`);
  }
  const module = path.join(dir, 'modules', `${OTHER_EXT}.so`);
  assert.ok(existsSync(module), `${module} is built`);
  const smoke = spawnSync('php', ['-n', '-d', `extension=${module}`, '-r', 'echo \\Acme\\Tool\\Order\\State::Draft->value, "\\n";'], { encoding: 'utf8' });
  assert.deepEqual([smoke.status, smoke.stdout], [0, '1\n'], smoke.stderr);
});
