// Tests of the rust backend (packages/fsm-compiler/src/backends/rust.mjs, docs/spec/fsm.md, B-4 and B-6; docs/plans/
// fsm-v1.md, C-2): the files of the order example are the golden files under tests/golden/rust, byte for byte, in the order
// the backend returns them, and the vector module is the golden tests/golden/rust/vectors.rs. The golden files were written by
// the generator once, after a review of its output against B-6 (docs/plans/fsm-v1.md, C-5). The command line writes the same
// files with gen --kind rust, and a file without the generated header is refused (E_NOT_GENERATED).
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test, { after } from 'node:test';
import { fileURLToPath } from 'node:url';
import { files, vectorsFile } from '../src/backends/rust.mjs';
import { backendOf, KINDS } from '../src/backends/index.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { vectors } from '../src/core/vectors.mjs';
import { jsonStore } from '../src/store-json/store.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const CLI = path.resolve(HERE, '../src/cli/fsm-gen.mjs');
const GOLDEN = path.join(HERE, 'golden/rust');
const SRC = ['order.rs', 'fsm.rs', 'lib.rs'];
const HEADER = /^\/\/ Code generated by fsm-gen from [^\n]+; DO NOT EDIT\.\n/;
const roots = [];

after(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

/** The IRs and the lock of the repository's definitions (the order example). */
async function orderIrs() {
  const { definitions, lock, findings } = await jsonStore(ROOT).load();
  assert.deepEqual(findings, []);
  return { irs: definitions.map(normalize), lock };
}

test('the rust kind is registered with its backend', () => {
  assert.ok(KINDS.includes('rust'));
  assert.equal(typeof backendOf('rust').files, 'function');
  assert.equal(typeof backendOf('rust').vectorsFile, 'function');
});

test('the files of the order example are the golden files, byte for byte, in the backend order', async () => {
  const { irs, lock } = await orderIrs();
  const out = files(irs, lock);
  assert.deepEqual(out.map(file => file.path), ['order.rs', 'fsm.rs', 'lib.rs']);
  for (const file of out) {
    assert.equal(file.content, readFileSync(path.join(GOLDEN, 'src', file.path), 'utf8'), `${file.path} differs from its golden file`);
  }
});

test('every generated file starts with the fsm-gen header of its machine or of fsm', async () => {
  const { irs, lock } = await orderIrs();
  for (const file of files(irs, lock)) {
    assert.match(file.content, HEADER, file.path);
    const from = file.path === 'order.rs' ? 'order' : 'fsm';
    assert.equal(file.content.split('\n')[0], `// Code generated by fsm-gen from ${from}; DO NOT EDIT.`, file.path);
    assert.ok(file.content.endsWith('\n') && !file.content.endsWith('\n\n'), `${file.path} must end with exactly one line break`);
  }
});

test('the vector module of the order example is the golden tests/vectors.rs, byte for byte', async () => {
  const { irs, lock } = await orderIrs();
  const generated = irs.map(ir => vectors(ir, lock));
  const text = vectorsFile(generated);
  assert.equal(text, readFileSync(path.join(GOLDEN, 'vectors.rs'), 'utf8'));
  assert.match(text, /^\/\/ Code generated by fsm-gen from fsm; DO NOT EDIT\.\n#!\[allow\(non_snake_case\)\]\n/);
  const names = [...text.matchAll(/^(?:async )?fn (test_\w+)\(\)/gm)].map(match => match[1]);
  assert.equal(names.length, 89, 'one test per vector case');
  assert.equal(new Set(names).size, names.length, 'every test has its own name');
});

test('the backend is deterministic: the same input gives the same files', async () => {
  const { irs, lock } = await orderIrs();
  assert.deepEqual(files(irs, lock), files(irs, lock));
});

test('a reserved code is named in from_code, and every other value is E_UNKNOWN_CODE', async () => {
  const { irs } = await orderIrs();
  const lock = { order: { codes: {}, reserved: [9] } };
  const order = files(irs, lock).find(file => file.path === 'order.rs').content;
  assert.match(order, /^\s+9 => Err\(Error::new\(Code::ReservedCode, /m);
  assert.match(order, /^\s+_ => Err\(Error::new\(Code::UnknownCode, /m);
});

test('gen --kind rust writes the golden src files, removes a stale generated file and exits 0', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'fsm-gen-rust-'));
  roots.push(root);
  const out = path.join(root, 'src');
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'stale.rs'), '// Code generated by fsm-gen from gone; DO NOT EDIT.\n');
  const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ROOT, '--kind', 'rust', '--out', out], { encoding: 'utf8' });
  assert.deepEqual([result.status, result.stdout, result.stderr], [0, '[fsm-gen] gen: ok\n', '']);
  for (const name of SRC) assert.equal(readFileSync(path.join(out, name), 'utf8'), readFileSync(path.join(GOLDEN, 'src', name), 'utf8'), name);
  assert.equal(existsSync(path.join(out, 'stale.rs')), false);
});

test('gen --kind rust refuses a hand-written file and writes nothing', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'fsm-gen-rust-'));
  roots.push(root);
  const out = path.join(root, 'src');
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'mine.rs'), 'pub fn mine() {}\n');
  const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ROOT, '--kind', 'rust', '--out', out], { encoding: 'utf8' });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /E_NOT_GENERATED/);
  assert.equal(existsSync(path.join(out, 'order.rs')), false);
  assert.equal(readFileSync(path.join(out, 'mine.rs'), 'utf8'), 'pub fn mine() {}\n');
});
