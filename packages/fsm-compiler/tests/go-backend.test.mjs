// Tests of the go backend (packages/fsm-compiler/src/backends/go.mjs, docs/spec/fsm.md, B-4 and B-6): the files of the
// order example are the golden files under tests/golden/go, byte for byte, in the order the backend returns them, and the
// vector file is the golden tests/vectors_test.go. The golden files were written by the generator once, after a review of its
// output against B-6 (docs/plans/fsm-v1.md, C-5). The generated machine packages import the shared package by the module
// path, so the module path is an input: the backend refuses to run without it, and gen --kind go needs --go-module.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { files, vectorsFile } from '../src/backends/go.mjs';
import { backendOf, KINDS } from '../src/backends/index.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { vectors } from '../src/core/vectors.mjs';
import { jsonStore } from '../src/store-json/store.mjs';
import { ORDER_PROJECT } from './order-project.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const CLI = path.resolve(HERE, '../src/cli/fsm-gen.mjs');
const GOLDEN = path.join(HERE, 'golden/go');
const MODULE = 'github.com/polyspec/fsm-go';
const NAMES = ['order/order.go', 'fsm/fsm.go'];
const HEADER = /^\/\/ Code generated by fsm-gen from [^\n]+; DO NOT EDIT\.\n/;

/** The IRs and the lock of the repository's definitions (the order example). */
async function orderIrs() {
  const { definitions, lock, findings } = await jsonStore(ORDER_PROJECT).load();
  assert.deepEqual(findings, []);
  return { irs: definitions.map(normalize), lock };
}

test('go is a registered kind of the compiler', () => {
  assert.ok(KINDS.includes('go'));
  assert.equal(backendOf('go').files, files);
});

test('the files of the order example are the golden files, byte for byte, in the backend order', async () => {
  const { irs, lock } = await orderIrs();
  const out = files(irs, lock, { module: MODULE });
  assert.deepEqual(out.map(file => file.path), NAMES);
  for (const file of out) {
    assert.equal(file.content, readFileSync(path.join(GOLDEN, 'src', file.path), 'utf8'), `${file.path} differs from its golden file`);
  }
});

test('every generated file starts with the fsm-gen header of its machine or of fsm', async () => {
  const { irs, lock } = await orderIrs();
  for (const file of files(irs, lock, { module: MODULE })) {
    assert.match(file.content, HEADER, file.path);
    const from = file.path.startsWith('order/') ? 'order' : 'fsm';
    assert.equal(file.content.split('\n')[0], `// Code generated by fsm-gen from ${from}; DO NOT EDIT.`, file.path);
    assert.ok(file.content.endsWith('\n') && !file.content.endsWith('\n\n'), `${file.path} must end with exactly one line break`);
  }
});

test('the machine imports the shared package by the module path of the input', async () => {
  const { irs, lock } = await orderIrs();
  const order = files(irs, lock, { module: 'example.org/other' }).find(file => file.path === 'order/order.go');
  assert.match(order.content, /"example\.org\/other\/src\/fsm"/);
});

test('the backend refuses a missing module path', async () => {
  const { irs, lock } = await orderIrs();
  assert.throws(() => files(irs, lock), /the module path of the package is required/);
  assert.throws(() => files(irs, lock, { module: '' }), /the module path of the package is required/);
  const generated = irs.map(ir => vectors(ir, lock));
  assert.throws(() => vectorsFile(generated), /the module path of the package is required/);
});

test('vectors --kind go without --go-module is a usage error and writes nothing', () => {
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-gen-go-'));
  try {
    const out = path.join(dir, 'vectors_test.go');
    const result = spawnSync(process.execPath, [CLI, 'vectors', '--project', ORDER_PROJECT, '--kind', 'go', '--out', out], { encoding: 'utf8' });
    assert.equal(result.status, 2);
    assert.match(result.stderr, /vectors --kind go needs --go-module <module path>/);
    assert.equal(existsSync(out), false);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('the vector file of the order example is the golden tests/vectors_test.go, byte for byte', async () => {
  const { irs, lock } = await orderIrs();
  const generated = irs.map(ir => vectors(ir, lock));
  assert.equal(vectorsFile(generated, { module: MODULE }), readFileSync(path.join(GOLDEN, 'vectors_test.go'), 'utf8'));
});

test('the backend is deterministic: the same input gives the same files', async () => {
  const { irs, lock } = await orderIrs();
  assert.deepEqual(files(irs, lock, { module: MODULE }), files(irs, lock, { module: MODULE }));
});

test('gen --kind go without --go-module is a usage error and writes nothing', () => {
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-gen-go-'));
  try {
    const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ORDER_PROJECT, '--kind', 'go', '--out', path.join(dir, 'src')], { encoding: 'utf8' });
    assert.equal(result.status, 2);
    assert.match(result.stderr, /gen --kind go needs --go-module <module path>/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('gen --kind go with --go-module writes the golden files', () => {
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-gen-go-'));
  try {
    const out = path.join(dir, 'src');
    const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ORDER_PROJECT, '--kind', 'go', '--go-module', MODULE, '--out', out], { encoding: 'utf8' });
    assert.deepEqual([result.status, result.stdout, result.stderr], [0, '[fsm-gen] gen: ok\n', '']);
    for (const name of NAMES) assert.equal(readFileSync(path.join(out, name), 'utf8'), readFileSync(path.join(GOLDEN, 'src', name), 'utf8'), name);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('--go-module is refused for another kind', () => {
  const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ORDER_PROJECT, '--kind', 'npm', '--go-module', MODULE, '--out', path.join(ROOT, 'var/unused')], { encoding: 'utf8' });
  assert.equal(result.status, 2);
  assert.match(result.stderr, /--go-module is an option of gen and vectors --kind go/);
});

test('a reserved code is E_RESERVED_CODE in FromCode, and the order example has none', async () => {
  const { irs, lock } = await orderIrs();
  const reserved = { order: { codes: lock.order.codes, reserved: [9] } };
  const order = files(irs, reserved, { module: MODULE }).find(file => file.path === 'order/order.go').content;
  assert.match(order, /\tcase 9:\n\t\treturn 0, &fsm\.Error\{Code: fsm\.CodeReservedCode, Message: "order: code 9 is reserved and is no state of order"\}\n/);
  const none = files(irs, lock, { module: MODULE }).find(file => file.path === 'order/order.go').content;
  assert.doesNotMatch(none, /CodeReservedCode, Message/);
});

/**
 * The hand-written declarations that a consumer's tests/ package holds next to the generated vectors file: the shapes of the
 * vector data and the helpers the adapters call (the same declarations as the test bed's tests/conformance_test.go). The
 * consumer does not get the persist example, so the file holds no import of the test bed.
 */
const CONSUMER_FIXTURE = `package tests

import (
	"fmt"
	"testing"
)

type machineVectors struct {
	machine string
	cases   []vectorCase
}

type vectorCase struct {
	feature         string
	id              string
	state           string
	event           string
	expected        string
	actual          string
	stored          string
	scenario        string
	value           int64
	hasValue        bool
	expectedValue   int64
	expectedIsValue bool
	actualValue     int64
	actualIsValue   bool
	input           int64
	code            int64
	want            expectation
}

type expectation struct {
	state       string
	to          string
	error       string
	changed     bool
	storedAfter string
	code        int64
	key         string
	final       bool
	events      []string
	expected    int32
	actual      int32
	event       int32
}

type stateArg struct {
	key     string
	value   int64
	isValue bool
}

type machineUnderTest interface {
	initial() (string, error)
	code(state stateArg) (int32, error)
	key(code int64) (string, error)
	fromCode(code int64) (string, error)
	isFinal(state stateArg) (bool, error)
	eventsFrom(state string) ([]string, error)
	target(expected, event string) (string, error)
	apply(expected stateArg, event string, actual stateArg) (string, bool, error)
	decide(expected, event string) func(stored int64) (int32, bool, error)
}

func int32Of(code int64) (int32, error) {
	if code != int64(int32(code)) {
		return 0, fmt.Errorf("%d is outside the 32-bit range of the states", code)
	}
	return int32(code), nil
}

func lookup[T any](table map[string]T, what, key string) (T, error) {
	value, ok := table[key]
	if !ok {
		var zero T
		return zero, fmt.Errorf("%q is no %s of the machine", key, what)
	}
	return value, nil
}

func keyOf[T comparable](table map[string]T, what string, value T) (string, error) {
	for key, candidate := range table {
		if candidate == value {
			return key, nil
		}
	}
	return "", fmt.Errorf("the %s %v has no key in the machine", what, value)
}

// TestMachines checks that every machine of the vectors has its adapter, the check the test bed's TestConformance starts with.
func TestMachines(t *testing.T) {
	for _, machine := range vectors {
		if _, ok := machines[machine.machine]; !ok {
			t.Fatalf("no adapter for the machine %s", machine.machine)
		}
	}
}
`;

test('a consumer module vets its vectors file with the generated src and no import of the test bed', async () => {
  const { irs, lock } = await orderIrs();
  const consumer = 'example.com/consumer';
  const dir = mkdtempSync(path.join(tmpdir(), 'fsm-go-consumer-'));
  try {
    writeFileSync(path.join(dir, 'go.mod'), `module ${consumer}\n\ngo 1.27\n`);
    for (const file of files(irs, lock, { module: consumer })) {
      const target = path.join(dir, 'src', file.path);
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, file.content);
    }
    mkdirSync(path.join(dir, 'tests'));
    writeFileSync(path.join(dir, 'tests/vectors_test.go'), vectorsFile(irs.map(ir => vectors(ir, lock)), { module: consumer }));
    writeFileSync(path.join(dir, 'tests/consumer_test.go'), CONSUMER_FIXTURE);
    const result = spawnSync('go', ['vet', './...'], { cwd: dir, encoding: 'utf8', env: { ...process.env, GOPROXY: 'off' } });
    assert.equal(result.status, 0, `${result.stdout}${result.stderr}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
