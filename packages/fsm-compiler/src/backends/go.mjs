// The go backend (docs/spec/fsm.md, B-4 and B-6; docs/plans/fsm-v1.md, C-2): the generated `src/` files of a go package
// and the native vector file `tests/vectors_test.go`. It takes the IRs of the machines (normalize.mjs), in definition order,
// the lock and the options { module }, the module path of the package, and returns the text of every file; it writes nothing.
// The output is deterministic: declaration order, tab indentation and a final line break. The generated code has no runtime
// dependency beyond the standard library and the shared package of the module (`<module>/src/fsm`), which the module path
// names: a Go import needs it, and the backend cannot read go.mod. The core imports nothing from node:.

import { forKind } from '../core/vectors.mjs';

const SHARED = 'fsm';
const KIND = 'go';

/** The name of a key in the pascal notation of B-6. Keys match ^[a-z][a-z0-9]*(_[a-z][a-z0-9]*)*$, so this is one-to-one. */
const pascal = key => key.split('_').map(word => word[0].toUpperCase() + word.slice(1)).join('');

/** The first line of a generated file (docs/spec/fsm.md, B-6). */
const header = from => `// Code generated by fsm-gen from ${from}; DO NOT EDIT.`;

/** The text of a list of lines: each line ends with a line break. */
const text = lines => `${lines.join('\n')}\n`;

/** A Go string literal of a value that holds no quote, backslash or control character (keys, codes and messages built here). */
const quoted = value => JSON.stringify(value);

/** The lines of `rows`, each a list of cells, with every column padded to its widest cell except the last one (gofmt alignment). */
function aligned(rows) {
  const widths = [];
  for (const row of rows) row.slice(0, -1).forEach((cell, index) => { widths[index] = Math.max(widths[index] ?? 0, cell.length); });
  return rows.map(row => row.map((cell, index) => (index < row.length - 1 ? cell.padEnd(widths[index] + 1) : cell)).join(''));
}

/** The shared package: the error codes of B-4, B-5 and B-6 that the functions throw, and the Error type of every machine. */
const FSM_GO = text([
  header(SHARED),
  '',
  '// Package fsm holds the error type and the error codes of the state machines (docs/spec/fsm.md, B-4 and B-6).',
  'package fsm',
  '',
  '// The error codes that the functions of every machine return.',
  'const (',
  ...aligned([
    ['\tCodeConflict', '= "E_CONFLICT"'],
    ['\tCodeInvalidTransition', '= "E_INVALID_TRANSITION"'],
    ['\tCodeUnknownCode', '= "E_UNKNOWN_CODE"'],
    ['\tCodeReservedCode', '= "E_RESERVED_CODE"'],
  ]),
  ')',
  '',
  '// Error is the error of a machine function. Expected, Actual and Event hold the arguments of the function that failed; zero',
  '// means unset, because a state code is at least 1 and an event position starts at 1.',
  'type Error struct {',
  ...aligned([
    ['\tCode', 'string'],
    ['\tMessage', 'string'],
    ['\tExpected', 'int32'],
    ['\tActual', 'int32'],
    ['\tEvent', 'int32'],
  ]),
  '}',
  '',
  '// Error returns the message of the error.',
  'func (e *Error) Error() string {',
  '\treturn e.Message',
  '}',
]);

/** The machine package of `ir` with its reserved codes from `lock`: the types, the members and the functions of B-6. */
function machineGo(ir, lock, { module }) {
  const { machine, initial, states, events, transitions } = ir;
  const reserved = [...lock[machine].reserved].sort((a, b) => a - b);
  const stateOf = key => `State${pascal(key)}`;
  const eventOf = key => `Event${pascal(key)}`;
  const outgoing = state => events.filter(event => transitions.some(item => item.state === state.key && item.event === event.key));
  const toOf = (state, event) => transitions.find(item => item.state === state && item.event === event).to;
  const lines = [
    header(machine),
    '',
    `// Package ${machine} is the state machine ${machine}: its states, its events and their functions (docs/spec/fsm.md, B-6).`,
    `package ${machine}`,
    '',
    'import (',
    '\t"fmt"',
    '',
    `\t"${module}/src/${SHARED}"`,
    ')',
    '',
    `// State is a state of ${machine}; its value is its code.`,
    'type State int32',
    '',
    `// The states of ${machine}.`,
    'const (',
    ...aligned(states.map(state => [`\t${stateOf(state.key)}`, 'State', `= ${state.code}`])),
    ')',
    '',
    `// Event is an event of ${machine}; its value is its position in the declaration, from 1.`,
    'type Event int32',
    '',
    `// The events of ${machine}.`,
    // An empty const block is written on one line, as gofmt prints it.
    ...(events.length === 0 ? ['const ()'] : [
      'const (',
      ...aligned(events.map((event, index) => [`\t${eventOf(event.key)}`, 'Event', `= ${index + 1}`])),
      ')',
    ]),
    '',
    '// Step is the result of Apply: the state that the event leads to, and whether the stored state changed.',
    'type Step struct {',
    ...aligned([['\tTo', 'State'], ['\tChanged', 'bool']]),
    '}',
    '',
    `// unknownState is the error of a value that is no state of ${machine}.`,
    'func unknownState(value int64) error {',
    `\treturn &fsm.Error{Code: fsm.CodeUnknownCode, Message: fmt.Sprintf("${machine}: %d is not a state of ${machine}", value)}`,
    '}',
    '',
    `// invalidTransition is the error of an event that has no edge from the state of ${machine}.`,
    'func invalidTransition(expected State, event Event) error {',
    `\treturn &fsm.Error{Code: fsm.CodeInvalidTransition, Message: fmt.Sprintf("${machine}: the event %d has no edge from %d", event, expected), Expected: int32(expected), Event: int32(event)}`,
    '}',
    '',
    `// Initial returns the initial state of ${machine}.`,
    'func Initial() State {',
    `\treturn ${stateOf(initial)}`,
    '}',
    '',
    '// Code returns the code of a state, which is its value; E_UNKNOWN_CODE for a value that is no state.',
    'func Code(state State) (int32, error) {',
    '\tswitch state {',
    ...states.map(state => `\tcase ${stateOf(state.key)}:\n\t\treturn ${state.code}, nil`),
    '\tdefault:',
    '\t\treturn 0, unknownState(int64(state))',
    '\t}',
    '}',
    '',
    '// Key returns the key of a state.',
    'func Key(state State) (string, error) {',
    '\tswitch state {',
    ...states.map(state => `\tcase ${stateOf(state.key)}:\n\t\treturn ${quoted(state.key)}, nil`),
    '\tdefault:',
    '\t\treturn "", unknownState(int64(state))',
    '\t}',
    '}',
    '',
    '// FromCode returns the state of a code: E_RESERVED_CODE for a reserved code, E_UNKNOWN_CODE for any other value.',
    'func FromCode(value int64) (State, error) {',
    '\tswitch value {',
    ...states.map(state => `\tcase ${state.code}:\n\t\treturn ${stateOf(state.key)}, nil`),
    ...reserved.map(item => `\tcase ${item}:\n\t\treturn 0, &fsm.Error{Code: fsm.CodeReservedCode, Message: "${machine}: code ${item} is reserved and is no state of ${machine}"}`),
    '\tdefault:',
    '\t\treturn 0, unknownState(value)',
    '\t}',
    '}',
    '',
    '// IsFinal reports whether a state is final.',
    'func IsFinal(state State) (bool, error) {',
    '\tswitch state {',
    ...states.map(state => `\tcase ${stateOf(state.key)}:\n\t\treturn ${state.final}, nil`),
    '\tdefault:',
    '\t\treturn false, unknownState(int64(state))',
    '\t}',
    '}',
    '',
    '// EventsFrom returns the events that have an edge from a state, in declaration order.',
    'func EventsFrom(state State) ([]Event, error) {',
    '\tswitch state {',
    ...states.map((state) => {
      const list = outgoing(state).map(event => eventOf(event.key));
      return `\tcase ${stateOf(state.key)}:\n\t\treturn []Event{${list.join(', ')}}, nil`;
    }),
    '\tdefault:',
    '\t\treturn nil, unknownState(int64(state))',
    '\t}',
    '}',
    '',
    '// Target returns the state that an event leads to from the expected state; E_INVALID_TRANSITION when the event has no edge from it.',
    'func Target(expected State, event Event) (State, error) {',
    '\tswitch expected {',
    ...states.flatMap((state) => {
      const edges = outgoing(state);
      if (edges.length === 0) return [`\tcase ${stateOf(state.key)}:\n\t\treturn 0, invalidTransition(expected, event)`];
      return [
        `\tcase ${stateOf(state.key)}:`,
        '\t\tswitch event {',
        ...edges.map(edge => `\t\tcase ${eventOf(edge.key)}:\n\t\t\treturn ${stateOf(toOf(state.key, edge.key))}, nil`),
        '\t\tdefault:',
        '\t\t\treturn 0, invalidTransition(expected, event)',
        '\t\t}',
      ];
    }),
    '\tdefault:',
    '\t\treturn 0, unknownState(int64(expected))',
    '\t}',
    '}',
    '',
    '// Apply applies an event that the observed state expected leads to, when the stored state is actual (docs/spec/fsm.md, B-4).',
    'func Apply(expected State, event Event, actual State) (Step, error) {',
    '\tto, err := Target(expected, event)',
    '\tif err != nil {',
    '\t\treturn Step{}, err',
    '\t}',
    '\tif _, err := Code(actual); err != nil {',
    '\t\treturn Step{}, err',
    '\t}',
    '\tif actual == expected {',
    '\t\treturn Step{To: to, Changed: true}, nil',
    '\t}',
    '\tif actual == to {',
    '\t\treturn Step{To: to, Changed: false}, nil',
    '\t}',
    `\treturn Step{}, &fsm.Error{Code: fsm.CodeConflict, Message: fmt.Sprintf("${machine}: the stored state %d is neither %d nor %d", actual, expected, to), Expected: int32(expected), Actual: int32(actual), Event: int32(event)}`,
    '}',
  ];
  return text(lines);
}

/**
 * The files of the go package `src/` for the machines `irs` (their IRs in definition order), the lock and the options
 * { module } (the module path of the package): `<machine>/<machine>.go` per machine, then `fsm/fsm.go`. Each file is
 * { path, content }, and the path is relative to `src/`.
 */
export function files(irs, lock, { module } = {}) {
  if (typeof module !== 'string' || module === '') throw new Error('go: the module path of the package is required');
  const out = [];
  for (const ir of irs) {
    if (!Object.hasOwn(lock, ir.machine)) throw new Error(`go: the lock has no entry for machine ${ir.machine}`);
    out.push({ path: `${ir.machine}/${ir.machine}.go`, content: machineGo(ir, lock, { module }) });
  }
  out.push({ path: `${SHARED}/${SHARED}.go`, content: FSM_GO });
  return out;
}

/** The Go field of each data field of the oracle (docs/plans/fsm-v1.md, C-4): a state value is an int64 with a flag. */
const DATA_FIELDS = {
  state: 'state', event: 'event', expected: 'expected', actual: 'actual', scenario: 'scenario', stored: 'stored',
  input: 'input', code: 'code', value: 'value', expected_value: 'expectedValue', actual_value: 'actualValue',
};

/** The Go literal of one vector case: its feature and id, its data fields, and its expectation (docs/plans/fsm-v1.md, C-4). */
function caseLiteral(entry) {
  const fields = [`feature: ${quoted(entry.feature)}`, `id: ${quoted(entry.id)}`, `name: ${quoted(entry.name)}`];
  const want = [];
  for (const [name, value] of Object.entries(entry)) {
    if (name === 'feature' || name === 'id' || name === 'name' || name === 'expect') continue;
    if (name === 'value' || name === 'expected_value' || name === 'actual_value') {
      const flag = { value: 'hasValue', expected_value: 'expectedIsValue', actual_value: 'actualIsValue' }[name];
      fields.push(`${DATA_FIELDS[name]}: ${integerLiteral(value, entry.id)}`, `${flag}: true`);
      continue;
    }
    if (name === 'input' || name === 'code') {
      fields.push(`${DATA_FIELDS[name]}: ${integerLiteral(value, entry.id)}`);
      continue;
    }
    const field = DATA_FIELDS[name];
    if (field === undefined || typeof value !== 'string') throw new Error(`go: the data field ${name} of ${entry.id} has no field`);
    fields.push(`${field}: ${quoted(value)}`);
  }
  const { expect } = entry;
  if (typeof expect === 'number') want.push(`code: ${expect}`);
  else if (typeof expect === 'string') want.push(`key: ${quoted(expect)}`);
  else if (typeof expect === 'boolean') want.push(`final: ${expect}`);
  else if (Array.isArray(expect)) want.push(`events: []string{${expect.map(quoted).join(', ')}}`);
  else {
    // A null field is not applicable to the error (B-6): the zero value of the Go field is unset, so the literal omits it.
    for (const [name, value] of Object.entries(expect)) {
      const field = { state: 'state', to: 'to', error: 'error', changed: 'changed', stored_after: 'storedAfter', expected: 'expected', actual: 'actual', event: 'event' }[name];
      if (field === undefined) throw new Error(`go: the expectation field ${name} of ${entry.id} has no field`);
      if (value === null) continue;
      want.push(`${field}: ${typeof value === 'string' ? quoted(value) : value}`);
    }
  }
  return `{${fields.join(', ')}, want: expectation{${want.join(', ')}}}`;
}

/** The Go literal of an integer data field, given as a decimal string (the 64-bit range stays exact) or as a safe integer. */
function integerLiteral(value, id) {
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  if (typeof value === 'string' && /^-?[0-9]+$/.test(value)) return value;
  throw new Error(`go: the integer ${JSON.stringify(value)} of ${id} is neither a safe integer nor a decimal string`);
}

/** The keys of a machine from its vector cases: a code case names every state and a target case names every event (core, vectors.mjs). */
function keysOf(cases) {
  const states = [...new Set(cases.filter(entry => entry.feature === 'code' && entry.state !== undefined).map(entry => entry.state))];
  const events = [...new Set(cases.filter(entry => entry.feature === 'target').map(entry => entry.event))];
  return { states, events };
}

/** A map variable of the Go type map[string]<type> with the rows [key, constant]; an empty map is one line (gofmt). */
function table(name, type, rows) {
  if (rows.length === 0) return [`var ${name} = map[string]${type}{}`];
  return [`var ${name} = map[string]${type}{`, ...aligned(rows.map(([key, value]) => [`\t${key}:`, `${value},`])), '}'];
}

/**
 * The adapter of one machine in tests/vectors_test.go: the key tables of its constants and the methods of the machineUnderTest
 * interface (declared by tests/conformance_test.go), which take keys (or the integers of invalid state values) and call the
 * generated functions of its package.
 */
function adapterOf(machine, cases) {
  const { states, events } = keysOf(cases);
  const stateConst = key => `${machine}.State${pascal(key)}`;
  const eventConst = key => `${machine}.Event${pascal(key)}`;
  const type = `${machine}Machine`;
  const statesTable = `${machine}States`;
  const eventsTable = `${machine}Events`;
  return [
    `// ${type} is the adapter of the ${machine} machine: its constants by key and its functions by key (docs/spec/fsm.md, B-6).`,
    `type ${type} struct{}`,
    '',
    `// ${statesTable} and ${eventsTable} map the keys of the ${machine} machine to its constants.`,
    ...table(statesTable, `${machine}.State`, states.map(key => [quoted(key), stateConst(key)])),
    '',
    ...table(eventsTable, `${machine}.Event`, events.map(key => [quoted(key), eventConst(key)])),
    '',
    `func (m ${type}) initial() (string, error) {`,
    `\treturn ${machine}.Key(${machine}.Initial())`,
    '}',
    '',
    `// state returns the state of a key, or the state that an integer names when the state type holds it (an invalid value included).`,
    `func (m ${type}) state(arg stateArg) (${machine}.State, error) {`,
    '\tif arg.isValue {',
    '\t\tvalue, err := int32Of(arg.value)',
    '\t\tif err != nil {',
    '\t\t\treturn 0, err',
    '\t\t}',
    `\t\treturn ${machine}.State(value), nil`,
    '\t}',
    `\treturn lookup(${statesTable}, "state", arg.key)`,
    '}',
    '',
    `func (m ${type}) code(state stateArg) (int32, error) {`,
    '\tvalue, err := m.state(state)',
    '\tif err != nil {',
    '\t\treturn 0, err',
    '\t}',
    `\treturn ${machine}.Code(value)`,
    '}',
    '',
    `func (m ${type}) key(code int64) (string, error) {`,
    '\tvalue, err := int32Of(code)',
    '\tif err != nil {',
    '\t\treturn "", err',
    '\t}',
    `\treturn ${machine}.Key(${machine}.State(value))`,
    '}',
    '',
    `func (m ${type}) fromCode(code int64) (string, error) {`,
    `\tvalue, err := ${machine}.FromCode(code)`,
    '\tif err != nil {',
    '\t\treturn "", err',
    '\t}',
    `\treturn ${machine}.Key(value)`,
    '}',
    '',
    `func (m ${type}) isFinal(state stateArg) (bool, error) {`,
    '\tvalue, err := m.state(state)',
    '\tif err != nil {',
    '\t\treturn false, err',
    '\t}',
    `\treturn ${machine}.IsFinal(value)`,
    '}',
    '',
    `func (m ${type}) eventsFrom(state string) ([]string, error) {`,
    `\tvalue, err := lookup(${statesTable}, "state", state)`,
    '\tif err != nil {',
    '\t\treturn nil, err',
    '\t}',
    `\tevents, err := ${machine}.EventsFrom(value)`,
    '\tif err != nil {',
    '\t\treturn nil, err',
    '\t}',
    '\tkeys := make([]string, 0, len(events))',
    '\tfor _, event := range events {',
    `\t\tkey, err := keyOf(${eventsTable}, "event", event)`,
    '\t\tif err != nil {',
    '\t\t\treturn nil, err',
    '\t\t}',
    '\t\tkeys = append(keys, key)',
    '\t}',
    '\treturn keys, nil',
    '}',
    '',
    `func (m ${type}) target(expected, event string) (string, error) {`,
    `\tfrom, err := lookup(${statesTable}, "state", expected)`,
    '\tif err != nil {',
    '\t\treturn "", err',
    '\t}',
    `\tvalue, err := lookup(${eventsTable}, "event", event)`,
    '\tif err != nil {',
    '\t\treturn "", err',
    '\t}',
    `\tto, err := ${machine}.Target(from, value)`,
    '\tif err != nil {',
    '\t\treturn "", err',
    '\t}',
    `\treturn keyOf(${statesTable}, "state", to)`,
    '}',
    '',
    `func (m ${type}) apply(expected stateArg, event string, actual stateArg) (string, bool, error) {`,
    '\tfrom, err := m.state(expected)',
    '\tif err != nil {',
    '\t\treturn "", false, err',
    '\t}',
    `\tvalue, err := lookup(${eventsTable}, "event", event)`,
    '\tif err != nil {',
    '\t\treturn "", false, err',
    '\t}',
    '\tobserved, err := m.state(actual)',
    '\tif err != nil {',
    '\t\treturn "", false, err',
    '\t}',
    `\tstep, err := ${machine}.Apply(from, value, observed)`,
    '\tif err != nil {',
    '\t\treturn "", false, err',
    '\t}',
    `\tto, err := keyOf(${statesTable}, "state", step.To)`,
    '\treturn to, step.Changed, err',
    '}',
    '',
    `func (m ${type}) decide(expected, event string) func(stored int64) (int32, bool, error) {`,
    '\treturn func(stored int64) (int32, bool, error) {',
    `\t\tfrom, err := lookup(${statesTable}, "state", expected)`,
    '\t\tif err != nil {',
    '\t\t\treturn 0, false, err',
    '\t\t}',
    `\t\tvalue, err := lookup(${eventsTable}, "event", event)`,
    '\t\tif err != nil {',
    '\t\t\treturn 0, false, err',
    '\t\t}',
    `\t\tobserved, err := ${machine}.FromCode(stored)`,
    '\t\tif err != nil {',
    '\t\t\treturn 0, false, err',
    '\t\t}',
    `\t\tstep, err := ${machine}.Apply(from, value, observed)`,
    '\t\tif err != nil {',
    '\t\t\treturn 0, false, err',
    '\t\t}',
    `\t\tcode, err := ${machine}.Code(step.To)`,
    '\t\treturn code, step.Changed, err',
    '\t}',
    '}',
  ];
}

/**
 * The native data file tests/vectors_test.go of `vectorList`, the vectors of every machine in order: the package `tests`, the
 * variable `vectors` of machineVectors (one literal per case), and per machine its adapter (adapterOf), which the variable
 * `machines` maps by machine key. The options { module } name the module path, which the imports of the machine packages need.
 */
export function vectorsFile(list, { module } = {}) {
  if (typeof module !== 'string' || module === '') throw new Error('go: the module path of the package is required');
  const vectorList = forKind(list, KIND);
  const lines = [
    header(SHARED),
    '',
    'package tests',
    '',
    'import (',
    ...vectorList.map(({ machine }) => `\t"${module}/src/${machine}"`),
    ')',
    '',
    '// vectors are the conformance vectors of the state machines, in the order of their definitions (docs/plans/fsm-v1.md, C-4).',
    '// Each case keeps the keys of the oracle; the adapter of its machine maps them to the constants of the machine.',
    'var vectors = []machineVectors{',
  ];
  for (const { machine, cases } of vectorList) {
    lines.push('\t{', `\t\tmachine: ${quoted(machine)},`, '\t\tcases: []vectorCase{');
    for (const entry of cases) lines.push(`\t\t\t${caseLiteral(entry)},`);
    lines.push('\t\t},', '\t},');
  }
  lines.push('}', '');
  lines.push('// machines maps the key of each machine to its adapter; the conformance test runs the cases of a machine through it.');
  lines.push(...table('machines', 'machineUnderTest', vectorList.map(({ machine }) => [quoted(machine), `${machine}Machine{}`])), '');
  for (const { machine, cases } of vectorList) lines.push(...adapterOf(machine, cases), '');
  return text(lines.slice(0, -1));
}
