// The tests that every backend has (docs/plans/fsm-v1/plan.md, C-5): its kind is registered, the files of the order example are the
// golden files byte for byte in the backend order, each file starts with the fsm-gen header of its machine or of fsm and ends with
// one line break, and the same input gives the same files. A backend test file calls backendTests and adds the tests of its kind.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { backendOf, KINDS } from '../src/backends/index.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { jsonStore } from '../src/store-json/store.mjs';
import { ORDER_PROJECT } from './order-project.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** The IRs and the lock of the repository's definitions (the order example). */
export async function orderIrs() {
  const { definitions, lock, findings } = await jsonStore(ORDER_PROJECT).load();
  assert.deepEqual(findings, []);
  return { irs: definitions.map(normalize), lock };
}

/**
 * Registers the tests that every backend has. `files` is the backend function and `options` its third argument; `names` are the
 * paths of the golden files in the backend order, under tests/golden/<kind>/src; `fromOf(file)` gives the machine or `fsm` that
 * a file is generated from; `headerLines(from, file)` gives the first lines that the file must have (by default the comment of
 * two slashes).
 */
export function backendTests({ kind, files, options, names, fromOf, headerLines = from => [`// Code generated by fsm-gen from ${from}; DO NOT EDIT.`] }) {
  const golden = path.join(HERE, 'golden', kind);
  const generated = async () => {
    const { irs, lock } = await orderIrs();
    return files(irs, lock, options);
  };

  test(`${kind} is a registered kind whose backend is the ${kind} module`, () => {
    assert.ok(KINDS.includes(kind));
    assert.equal(backendOf(kind).files, files);
  });

  test('the files of the order example are the golden files, byte for byte, in the backend order', async () => {
    const out = await generated();
    assert.deepEqual(out.map(file => file.path), names);
    for (const file of out) {
      assert.equal(file.content, readFileSync(path.join(golden, 'src', file.path), 'utf8'), `${file.path} differs from its golden file`);
    }
  });

  test('every generated file starts with the fsm-gen header of its machine or of fsm, and ends with one line break', async () => {
    for (const file of await generated()) {
      const expected = headerLines(fromOf(file.path), file.path);
      assert.deepEqual(file.content.split('\n').slice(0, expected.length), expected, file.path);
      assert.ok(file.content.endsWith('\n') && !file.content.endsWith('\n\n'), `${file.path} must end with exactly one line break`);
    }
  });

  test('the backend is deterministic: the same input gives the same files', async () => {
    assert.deepEqual(await generated(), await generated());
  });
}
