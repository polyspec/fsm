// Tests of the rust backend (packages/compiler/src/backends/rust.mjs, docs/spec/fsm.md, B-4 and B-6; docs/plans/
// fsm-v1.md, C-2): the files of the order example are the golden files under tests/golden/rust, byte for byte, in the order
// the backend returns them. The golden files were written by
// the generator once, after a review of its output against B-6 (docs/plans/fsm-v1/plan.md, C-5). The command line writes the same
// files with gen --kind rust, and a file without the generated header is refused (E_NOT_GENERATED).
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test, { after } from 'node:test';
import { files } from '../src/backends/rust.mjs';
import { normalize } from '../src/core/normalize.mjs';
import { validate } from '../src/core/validate.mjs';
import { backendTests, orderIrs } from './backend-support.mjs';
import { CLI, HERE } from './cli-support.mjs';
import { ORDER_PROJECT } from './order-project.mjs';

const GOLDEN = path.join(HERE, 'golden/rust');
const SRC = ['order.rs', 'fsm.rs', 'lib.rs'];
const roots = [];

after(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

backendTests({ kind: 'rust', files, names: SRC, fromOf: file => (file === 'order.rs' ? 'order' : 'fsm') });

test('a reserved code is named in from_code, and every other value is E_UNKNOWN_CODE', async () => {
  const { irs } = await orderIrs();
  const lock = { order: { codes: {}, reserved: [9] } };
  const order = files(irs, lock).find(file => file.path === 'order.rs').content;
  assert.match(order, /^\s+9 => Err\(Error::new\(Code::ReservedCode, /m);
  assert.match(order, /^\s+_ => Err\(Error::new\(Code::UnknownCode, /m);
});

test('gen --kind rust writes the golden src files, removes a stale generated file and exits 0', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'fsm-gen-rust-'));
  roots.push(root);
  const out = path.join(root, 'src');
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'stale.rs'), '// Code generated by fsm-gen from gone; DO NOT EDIT.\n');
  const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ORDER_PROJECT, '--kind', 'rust', '--out', out], { encoding: 'utf8' });
  assert.deepEqual([result.status, result.stdout, result.stderr], [0, '[fsm-gen] gen: ok\n', '']);
  for (const name of SRC) assert.equal(readFileSync(path.join(out, name), 'utf8'), readFileSync(path.join(GOLDEN, 'src', name), 'utf8'), name);
  assert.equal(existsSync(path.join(out, 'stale.rs')), false);
});

test('gen --kind rust refuses a hand-written file and writes nothing', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'fsm-gen-rust-'));
  roots.push(root);
  const out = path.join(root, 'src');
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, 'mine.rs'), 'pub fn mine() {}\n');
  const result = spawnSync(process.execPath, [CLI, 'gen', '--project', ORDER_PROJECT, '--kind', 'rust', '--out', out], { encoding: 'utf8' });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /E_NOT_GENERATED/);
  assert.equal(existsSync(path.join(out, 'order.rs')), false);
  assert.equal(readFileSync(path.join(out, 'mine.rs'), 'utf8'), 'pub fn mine() {}\n');
});

/** A machine without events: its one state is the initial and the final state, so no edge is needed (docs/spec/fsm.md, B-5). */
const NO_EVENTS = { machine: 'one', states: [{ key: 'only', code: 3, initial: true, final: true }], events: [] };
const NO_EVENTS_LOCK = { one: { codes: { 3: 'only' }, reserved: [1] } };

test('a machine without events has an Event enum with no #[repr(i32)] (a zero-variant enum takes no representation)', () => {
  assert.deepEqual(validate([NO_EVENTS]), []);
  const one = files([normalize(NO_EVENTS)], NO_EVENTS_LOCK).find(file => file.path === 'one.rs').content;
  assert.match(one, /\n#\[derive\(Debug, Clone, Copy, PartialEq, Eq\)\]\npub enum Event \{\n\}\n/);
  assert.doesNotMatch(one, /#\[repr\(i32\)\]\n#\[derive\(Debug, Clone, Copy, PartialEq, Eq\)\]\npub enum Event/);
});

test('the src files of a machine without events build with cargo', () => {
  const root = mkdtempSync(path.join(tmpdir(), 'fsm-rust-noevents-'));
  roots.push(root);
  mkdirSync(path.join(root, 'src'));
  writeFileSync(path.join(root, 'Cargo.toml'), '[package]\nname = "noevents"\nversion = "0.0.0"\nedition = "2021"\n\n[lib]\npath = "src/lib.rs"\n\n[dependencies]\nserde_json = "1.0.151"\n');
  for (const file of files([normalize(NO_EVENTS)], NO_EVENTS_LOCK)) writeFileSync(path.join(root, 'src', file.path), file.content);
  const result = spawnSync('cargo', ['build', '--quiet', '--manifest-path', path.join(root, 'Cargo.toml')], { encoding: 'utf8' });
  assert.deepEqual([result.status, result.stderr], [0, ''], 'cargo build of a machine without events');
});
